// Builds src/skills/motion-files.generated.ts from src/skills/motion-graphics-videos/.
// The skill's files are written as real files (Markdown with code fences, an HTML starter,
// Node scripts) and embedded as JSON strings, so nothing in them needs escaping by hand.
// Run after editing any of them: npm run gen:motion. A test fails when this is out of date.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, "..", "src", "skills", "motion-graphics-videos");
const out = path.join(here, "..", "src", "skills", "motion-files.generated.ts");

export function render() {
  const read = (p) => fs.readFileSync(path.join(dir, p), "utf8").replace(/\r\n/g, "\n");
  const files = [];
  for (const sub of ["references", "assets", "scripts"]) {
    for (const name of fs.readdirSync(path.join(dir, sub)).sort()) files.push(`${sub}/${name}`);
  }
  const lines = [
    "// Generated by scripts/gen-motion-skill.mjs from src/skills/motion-graphics-videos/. Do not edit by hand.",
    "",
    `export const MOTION_BODY: string = ${JSON.stringify(read("SKILL.md").trim())};`,
    "",
    "export const MOTION_FILES: Record<string, string> = {",
    ...files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(read(f).trim())},`),
    "};",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(out, render());
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}
